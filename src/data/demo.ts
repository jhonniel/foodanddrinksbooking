function makeProduct(
  id: string,
  categoryId: string,
  name: string,
  slug: string,
  description: string,
  price: number,
  image: string,
  flags: Partial<Product> = {}
): Product {
  const options = defaultOptions().map((o, i) => ({
    ...o,
    id: `${id}-opt-${i}`,
    product_id: id,
    values: o.values?.map((v, vi) => ({
      ...v,
      id: `${id}-opt-${i}-val-${vi}`,
      option_id: `${id}-opt-${i}`,
    })),
  }));
  return {
    id,
    category_id: categoryId,
    name,
    slug,
    description,
    base_price: price,
    image_url: image,
    sku: `IC-${slug.toUpperCase().slice(0, 8)}`,
    is_available: true,
    is_featured: false,
    is_best_seller: false,
    is_new: false,
    preparation_time_minutes: 10,
    rating: 4.7,
    review_count: 50,
    sort_order: 0,
    created_at: new Date().toISOString(),
    updated_at: new Date().toISOString(),
    options,
    addons: ADDONS,
    ...flags,
  };
}

